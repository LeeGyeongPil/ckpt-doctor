def _flatten(codes: dict[str, tuple[str, str, str, str]], ui: dict[str, str]) -> dict[str, str]:
    out = dict(ui)
    for code, (title, msg, cause, fix) in codes.items():
        out[f"{code}.title"] = title
        out[f"{code}.msg"] = msg
        out[f"{code}.cause"] = cause
        out[f"{code}.fix"] = fix
    return out


